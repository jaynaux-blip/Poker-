// ---------------------------------------------------------------------------------------------------------- files

bool ReadFile(const std::string& Path, std::string& Out)
{
	FILE* F = std::fopen(Path.c_str(), "rb");
	if (!F)
	{
		return false;
	}
	Out.clear();
	char Buf[65536];
	size_t N = 0;
	while ((N = std::fread(Buf, 1, sizeof(Buf), F)) > 0)
	{
		Out.append(Buf, N);
	}
	std::fclose(F);
	// Line endings never matter (the checksum and the parser see LF only).
	Out.erase(std::remove(Out.begin(), Out.end(), '\r'), Out.end());
	return true;
}

bool WriteFile(const std::string& Path, const std::string& Text)
{
	FILE* F = std::fopen(Path.c_str(), "wb");
	if (!F)
	{
		std::printf("chartgen: can't write %s\n", Path.c_str());
		return false;
	}
	std::fwrite(Text.data(), 1, Text.size(), F);
	std::fclose(F);
	return true;
}

/** The chart texts, in the order the checksum reads them (style_test lists the same four). */
const std::vector<std::string>& ChartFiles()
{
	static const std::vector<std::string> Files = {"gto_preflop.txt", "nash_push.txt", "nash_call.txt", "nash_reshove.txt"};
	return Files;
}

uint64_t Checksum(const std::string& Dir, bool& Ok)
{
	uint64_t H = 14695981039346656037ull;
	Ok = true;
	for (const std::string& Name : ChartFiles())
	{
		std::string Text;
		if (!ReadFile(Dir + "/" + Name, Text))
		{
			std::printf("chartgen: missing %s/%s\n", Dir.c_str(), Name.c_str());
			Ok = false;
			continue;
		}
		for (const char Ch : Name + "\n" + Text)
		{
			H = (H ^ static_cast<unsigned char>(Ch)) * 1099511628211ull;
		}
	}
	return H;
}

std::vector<std::string> Split(const std::string& Line, char Sep)
{
	std::vector<std::string> Out;
	std::string Cur;
	for (const char Ch : Line)
	{
		if (Ch == Sep)
		{
			if (!Cur.empty())
			{
				Out.push_back(Cur);
			}
			Cur.clear();
		}
		else
		{
			Cur += Ch;
		}
	}
	if (!Cur.empty())
	{
		Out.push_back(Cur);
	}
	return Out;
}

// ---------------------------------------------------------------------------------------------------------- ranges

bool Has(const Bits& B, int Cls) { return (B[static_cast<size_t>(Cls / 64)] >> (Cls % 64)) & 1u; }
void Set(Bits& B, int Cls) { B[static_cast<size_t>(Cls / 64)] |= uint64_t(1) << (Cls % 64); }

int RankIndex(char Ch)
{
	const char* P = std::strchr(ss::RankChars, Ch);
	return P && Ch ? static_cast<int>(P - ss::RankChars) : -1;
}

/** The class of a pair (Hi == Lo) or of two ranks suited or offsuit (Hi > Lo). */
int ClassOf(int Hi, int Lo, bool Suited)
{
	const int Row = 12 - Hi;
	const int Col = 12 - Lo;
	if (Hi == Lo)
	{
		return Row * 13 + Col;
	}
	return Suited ? Row * 13 + Col : Col * 13 + Row;
}

/** One token: "AA", "QQ+", "22-77", "AKs", "AK", "A2s+", "K9s-K6s", "ATo+". False when it isn't one. */
bool ParseToken(const std::string& Tok, Bits& Out)
{
	if (Tok.size() < 2)
	{
		return false;
	}
	const int A = RankIndex(Tok[0]);
	const int B = RankIndex(Tok[1]);
	if (A < 0 || B < 0)
	{
		return false;
	}
	size_t I = 2;
	int Kind = 2; // 0 suited, 1 offsuit, 2 both
	if (I < Tok.size() && (Tok[I] == 's' || Tok[I] == 'o'))
	{
		Kind = Tok[I] == 's' ? 0 : 1;
		++I;
	}
	const bool Pair = A == B;
	const int Hi = std::max(A, B);
	int LoFrom = std::min(A, B);
	int LoTo = LoFrom;
	if (I < Tok.size() && Tok[I] == '+')
	{
		LoTo = Pair ? 12 : Hi - 1;
		++I;
	}
	else if (I < Tok.size() && Tok[I] == '-')
	{
		const std::string Rest = Tok.substr(I + 1);
		if (Rest.size() < 2)
		{
			return false;
		}
		const int C = RankIndex(Rest[0]);
		const int D = RankIndex(Rest[1]);
		if (C < 0 || D < 0)
		{
			return false;
		}
		if (Pair)
		{
			LoFrom = std::min(A, C);
			LoTo = std::max(A, C);
		}
		else
		{
			if (std::max(C, D) != Hi)
			{
				return false;
			}
			LoFrom = std::min(std::min(A, B), std::min(C, D));
			LoTo = std::max(std::min(A, B), std::min(C, D));
		}
		I = Tok.size();
	}
	if (I != Tok.size())
	{
		return false;
	}
	for (int Lo = LoFrom; Lo <= LoTo; ++Lo)
	{
		if (Pair)
		{
			Set(Out, ClassOf(Lo, Lo, false));
			continue;
		}
		if (Kind != 1)
		{
			Set(Out, ClassOf(Hi, Lo, true));
		}
		if (Kind != 0)
		{
			Set(Out, ClassOf(Hi, Lo, false));
		}
	}
	return true;
}

bool ParseRange(const std::string& Text, Bits& Out)
{
	Out = Bits{0, 0, 0};
	if (Text == "-")
	{
		return true;
	}
	for (const std::string& Tok : Split(Text, ','))
	{
		if (!ParseToken(Tok, Out))
		{
			std::printf("chartgen: not a range token: \"%s\"\n", Tok.c_str());
			return false;
		}
	}
	return true;
}

/** Kicker runs for one high rank: "A2s+", "K9s-K6s", "Q8o". */
void FormatRuns(int Hi, bool Suited, const Bits& B, std::vector<std::string>& Out)
{
	const char Tag = Suited ? 's' : 'o';
	int Lo = Hi - 1;
	while (Lo >= 0)
	{
		if (!Has(B, ClassOf(Hi, Lo, Suited)))
		{
			--Lo;
			continue;
		}
		const int Top = Lo;
		while (Lo - 1 >= 0 && Has(B, ClassOf(Hi, Lo - 1, Suited)))
		{
			--Lo;
		}
		std::string T;
		T += ss::RankChars[Hi];
		if (Top == Hi - 1 && Lo < Top)
		{
			T += ss::RankChars[Lo];
			T += Tag;
			T += '+';
		}
		else if (Lo == Top)
		{
			T += ss::RankChars[Top];
			T += Tag;
		}
		else
		{
			T += ss::RankChars[Top];
			T += Tag;
			T += '-';
			T += ss::RankChars[Hi];
			T += ss::RankChars[Lo];
			T += Tag;
		}
		Out.push_back(T);
		--Lo;
	}
}

std::string FormatRange(const Bits& B)
{
	std::vector<std::string> Out;
	// Pairs, top down: "QQ+", "88-55", "22".
	int R = 12;
	while (R >= 0)
	{
		if (!Has(B, ClassOf(R, R, false)))
		{
			--R;
			continue;
		}
		const int Top = R;
		while (R - 1 >= 0 && Has(B, ClassOf(R - 1, R - 1, false)))
		{
			--R;
		}
		std::string T;
		T += ss::RankChars[Top];
		T += ss::RankChars[Top];
		if (Top == 12 && R < Top)
		{
			T = std::string() + ss::RankChars[R] + ss::RankChars[R] + "+";
		}
		else if (R < Top)
		{
			T += std::string("-") + ss::RankChars[R] + ss::RankChars[R];
		}
		Out.push_back(T);
		--R;
	}
	for (int Hi = 12; Hi >= 1; --Hi)
	{
		FormatRuns(Hi, true, B, Out);
		FormatRuns(Hi, false, B, Out);
	}
	if (Out.empty())
	{
		return "-";
	}
	std::string S;
	for (const std::string& T : Out)
	{
		S += (S.empty() ? "" : ",") + T;
	}
	return S;
}

