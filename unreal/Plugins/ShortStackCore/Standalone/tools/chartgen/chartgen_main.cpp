/** Every combo of each class (two cards). */
std::vector<std::vector<std::array<int, 2>>> CombosByClass()
{
	std::vector<std::vector<std::array<int, 2>>> Out(Classes);
	for (int A = 0; A < 52; ++A)
	{
		for (int B = A + 1; B < 52; ++B)
		{
			Out[static_cast<size_t>(ss::HandClass(A, B))].push_back({A, B});
		}
	}
	return Out;
}

struct Matrices
{
	std::vector<double> Eq;     // [i * 169 + j]: class i's pot share against class j
	std::vector<double> Compat; // [i * 169 + j]: combos of j that share no card with a combo of i, averaged over i's combos
};

void BuildCompat(Matrices& M)
{
	const auto Combos = CombosByClass();
	M.Compat.assign(Classes * Classes, 0.0);
	for (int I = 0; I < Classes; ++I)
	{
		for (int J = 0; J < Classes; ++J)
		{
			double Sum = 0;
			for (const auto& X : Combos[static_cast<size_t>(I)])
			{
				for (const auto& Y : Combos[static_cast<size_t>(J)])
				{
					Sum += (X[0] != Y[0] && X[0] != Y[1] && X[1] != Y[0] && X[1] != Y[1]) ? 1.0 : 0.0;
				}
			}
			M.Compat[static_cast<size_t>(I * Classes + J)] = Sum / static_cast<double>(Combos[static_cast<size_t>(I)].size());
		}
	}
}

/** The 169 x 169 matrix, 10,000 samples a pair from a fixed seed; cached beside the tool. */
bool BuildEquity(Matrices& M, const std::string& Cache)
{
	M.Eq.assign(Classes * Classes, 0.5);
	FILE* F = std::fopen(Cache.c_str(), "rb");
	if (F)
	{
		const size_t Got = std::fread(M.Eq.data(), sizeof(double), M.Eq.size(), F);
		std::fclose(F);
		if (Got == M.Eq.size())
		{
			std::printf("chartgen: equity matrix from %s\n", Cache.c_str());
			return true;
		}
	}
	std::printf("chartgen: sampling the equity matrix (10,000 a pair)...\n");
	const auto Combos = CombosByClass();
	ss::Rng R("chartgen:equity169");
	for (int I = 0; I < Classes; ++I)
	{
		for (int J = I; J < Classes; ++J)
		{
			const auto& Ci = Combos[static_cast<size_t>(I)];
			const auto& Cj = Combos[static_cast<size_t>(J)];
			double Won = 0;
			int Samples = 0;
			while (Samples < 10000)
			{
				const auto& X = Ci[static_cast<size_t>(R.Int(static_cast<int>(Ci.size())))];
				const auto& Y = Cj[static_cast<size_t>(R.Int(static_cast<int>(Cj.size())))];
				if (X[0] == Y[0] || X[0] == Y[1] || X[1] == Y[0] || X[1] == Y[1])
				{
					continue;
				}
				int Deck[48];
				int N = 0;
				for (int C = 0; C < 52; ++C)
				{
					if (C != X[0] && C != X[1] && C != Y[0] && C != Y[1])
					{
						Deck[N++] = C;
					}
				}
				int A[7] = {X[0], X[1], 0, 0, 0, 0, 0};
				int B[7] = {Y[0], Y[1], 0, 0, 0, 0, 0};
				for (int K = 0; K < 5; ++K)
				{
					const int Pick = K + R.Int(48 - K);
					std::swap(Deck[K], Deck[Pick]);
					A[2 + K] = Deck[K];
					B[2 + K] = Deck[K];
				}
				const int Sa = ss::Evaluate(A, 7);
				const int Sb = ss::Evaluate(B, 7);
				Won += Sa > Sb ? 1.0 : Sa == Sb ? 0.5 : 0.0;
				++Samples;
			}
			const double E = Won / Samples;
			M.Eq[static_cast<size_t>(I * Classes + J)] = E;
			M.Eq[static_cast<size_t>(J * Classes + I)] = 1.0 - E;
		}
		if (I % 20 == 0)
		{
			std::printf("  row %d of 169\n", I);
		}
	}
	F = std::fopen(Cache.c_str(), "wb");
	if (F)
	{
		std::fwrite(M.Eq.data(), sizeof(double), M.Eq.size(), F);
		std::fclose(F);
	}
	return true;
}

