/** Seat order, 9-max: 0 UTG .. 6 BTN, 7 SB, 8 BB. */
const char* const PosNames[9] = {"UTG", "UTG1", "MP", "LJ", "HJ", "CO", "BTN", "SB", "BB"};

int PosIndex(const std::string& Name)
{
	for (int I = 0; I < 9; ++I)
	{
		if (Name == PosNames[I])
		{
			return I;
		}
	}
	return -1;
}

/** Against a range (a strategy per class, 0..1): the share of compatible combos it holds, and the equity against it. */
struct Versus
{
	double Weight = 0; // compatible combos in the range
	double Total = 0;  // compatible combos at all
	double Equity = 0.5;
};

Versus Against(const Matrices& M, int Hand, const std::vector<double>& Range)
{
	Versus V;
	double EqSum = 0;
	const double* Cp = &M.Compat[static_cast<size_t>(Hand * Classes)];
	const double* Ep = &M.Eq[static_cast<size_t>(Hand * Classes)];
	for (int C = 0; C < Classes; ++C)
	{
		const double W = Cp[C] * Range[static_cast<size_t>(C)];
		V.Total += Cp[C];
		V.Weight += W;
		EqSum += W * Ep[C];
	}
	V.Equity = V.Weight > 0 ? EqSum / V.Weight : 0.5;
	return V;
}

/** Posts before the action, in big blinds: the small blind, the big blind and its ante (dead). */
double BlindOf(int Pos) { return Pos == 7 ? 0.5 : Pos == 8 ? 1.0 : 0.0; }

/**
 * A first-in jam from Pos at depth E (every stack E before the posts), answered by the players behind in order, the first
 * caller only. Returns the jam range and each caller's range (index = caller position).
 */
struct PushSolution
{
	std::vector<double> Jam;
	std::vector<std::vector<double>> Call; // [caller position]
};

PushSolution SolvePush(const Matrices& M, int Pos, double E, double Ante, const PushSolution* Warm)
{
	PushSolution S;
	S.Jam.assign(Classes, 0.3);
	S.Call.assign(9, std::vector<double>(Classes, 0.15));
	if (Warm)
	{
		S = *Warm;
	}
	std::vector<int> Callers;
	for (int P = Pos + 1; P <= 8; ++P)
	{
		Callers.push_back(P);
	}
	// What each caller would match, the pot it plays for, and the jammer's posts.
	const double DeadAll = 0.5 + 1.0 + Ante - BlindOf(Pos); // everything the others posted
	std::vector<double> Matched(9, 0), Pot(9, 0);
	for (const int C : Callers)
	{
		const double Live = C == 8 ? E - Ante : E;
		Matched[static_cast<size_t>(C)] = std::min(E, Live);
		double Dead = Ante;
		Dead += (Pos != 7 && C != 7) ? 0.5 : 0.0;
		Dead += (C != 8) ? 1.0 : 0.0; // the big blind's blind, when the big blind isn't in it
		Pot[static_cast<size_t>(C)] = 2.0 * Matched[static_cast<size_t>(C)] + Dead;
	}
	const int Iterations = Warm ? 200 : 400;
	for (int It = 0; It < Iterations; ++It)
	{
		const double Step = 1.0 / static_cast<double>(It + 2);
		// The jammer's best response to the callers' average ranges.
		std::vector<double> JamBr(Classes, 0.0);
		for (int H = 0; H < Classes; ++H)
		{
			double Reach = 1.0;
			double Ev = 0;
			for (const int C : Callers)
			{
				const Versus V = Against(M, H, S.Call[static_cast<size_t>(C)]);
				const double Q = V.Total > 0 ? V.Weight / V.Total : 0.0;
				Ev += Reach * Q * (V.Equity * Pot[static_cast<size_t>(C)] - Matched[static_cast<size_t>(C)]);
				Reach *= 1.0 - Q;
			}
			Ev += Reach * DeadAll;
			Ev += BlindOf(Pos); // against folding (which loses the jammer's own blind)
			JamBr[static_cast<size_t>(H)] = Ev > 0 ? 1.0 : 0.0;
		}
		// Each caller's best response to the jammer's average range.
		for (const int C : Callers)
		{
			std::vector<double>& Cr = S.Call[static_cast<size_t>(C)];
			for (int H = 0; H < Classes; ++H)
			{
				const Versus V = Against(M, H, S.Jam);
				const double Ev = V.Weight > 0 ? V.Equity * Pot[static_cast<size_t>(C)] - Matched[static_cast<size_t>(C)] + BlindOf(C) : -1.0;
				Cr[static_cast<size_t>(H)] += ((Ev > 0 ? 1.0 : 0.0) - Cr[static_cast<size_t>(H)]) * Step;
			}
		}
		for (int H = 0; H < Classes; ++H)
		{
			S.Jam[static_cast<size_t>(H)] += (JamBr[static_cast<size_t>(H)] - S.Jam[static_cast<size_t>(H)]) * Step;
		}
	}
	return S;
}

/**
 * One open (to 2 BB) from the opener's range, a re-jam from Me at depth E, the opener's call (the players between them and
 * behind fold: the first-caller simplification). Me: 0 in position (no blind), 1 the small blind, 2 the big blind.
 */
struct ReshoveSolution
{
	std::vector<double> Jam, Call;
};

ReshoveSolution SolveReshove(const Matrices& M, const std::vector<double>& Open, bool OpenerIsSb, int Me, double E, double Ante)
{
	ReshoveSolution S;
	S.Jam.assign(Classes, 0.1);
	S.Call.assign(Classes, 0.3);
	// Results against the start of the hand, in big blinds. The opener's 2 BB includes its blind when it's the small blind;
	// the ante is the big blind's, dead either way.
	const double MyBlind = Me == 1 ? 0.5 : Me == 2 ? 1.0 : 0.0;
	const double MyAnte = Me == 2 ? Ante : 0.0;
	const double Matched = E - MyAnte; // the opener isn't the big blind, so the big blind's live stack is the short one
	const double OtherBlinds = (Me != 1 && !OpenerIsSb ? 0.5 : 0.0) + (Me != 2 ? 1.0 : 0.0);
	const double PotCalled = 2.0 * Matched + OtherBlinds + Ante;
	const double WinFolded = 2.0 + OtherBlinds + (Ante - MyAnte); // what I take from the others when the opener folds
	for (int It = 0; It < 400; ++It)
	{
		const double Step = 1.0 / static_cast<double>(It + 2);
		std::vector<double> JamBr(Classes, 0.0);
		std::vector<double> CallsAgainst(Classes, 0.0);
		for (int C = 0; C < Classes; ++C)
		{
			CallsAgainst[static_cast<size_t>(C)] = Open[static_cast<size_t>(C)] * S.Call[static_cast<size_t>(C)];
		}
		for (int H = 0; H < Classes; ++H)
		{
			const Versus All = Against(M, H, Open);
			const Versus Calls = Against(M, H, CallsAgainst);
			const double Q = All.Weight > 0 ? Calls.Weight / All.Weight : 0.0;
			// Against folding, which loses my blind and my ante.
			const double Ev = (1.0 - Q) * WinFolded + Q * (Calls.Equity * PotCalled - Matched - MyAnte) + MyBlind + MyAnte;
			JamBr[static_cast<size_t>(H)] = Ev > 0 ? 1.0 : 0.0;
		}
		for (int C = 0; C < Classes; ++C)
		{
			const Versus V = Against(M, C, S.Jam);
			const double Ev = V.Weight > 0 ? V.Equity * PotCalled - Matched + 2.0 : -1.0;
			S.Call[static_cast<size_t>(C)] += ((Ev > 0 ? 1.0 : 0.0) - S.Call[static_cast<size_t>(C)]) * Step;
		}
		for (int H = 0; H < Classes; ++H)
		{
			S.Jam[static_cast<size_t>(H)] += (JamBr[static_cast<size_t>(H)] - S.Jam[static_cast<size_t>(H)]) * Step;
		}
	}
	return S;
}

Bits Pure(const std::vector<double>& Strategy)
{
	Bits B{0, 0, 0};
	for (int H = 0; H < Classes; ++H)
	{
		if (Strategy[static_cast<size_t>(H)] >= 0.5)
		{
			Set(B, H);
		}
	}
	return B;
}

double ShareOf(const Bits& B)
{
	int Combos = 0;
	for (int H = 0; H < Classes; ++H)
	{
		Combos += Has(B, H) ? ss::HandClassCombos(H) : 0;
	}
	return static_cast<double>(Combos) / 1326.0;
}

