// ------------------------------------------------------------------ hands (random legal actions)

{
  const r = new Rng('hands');
  for (let t = 0; t < 400; t++) {
    const n = 2 + r.int(8);
    const stacks = Array.from({ length: n }, () => 1 + r.int(20000));
    const button = r.int(n);
    const ante = r.chance(0.5) ? 100 : 0;
    const seed = `hand${t}`;
    const h = new Hand({ players: stacks.map((stack, seat) => ({ seat, id: `p${seat}`, stack })), buttonSeat: button, smallBlind: 50, bigBlind: 100, ante, rng: new Rng(seed) });
    const actions: string[] = [];
    while (!h.complete) {
      const legal = h.legalActions();
      const roll = r.next();
      let a: PlayerAction;
      if (roll < 0.15) a = { type: 'fold' };
      else if (roll < 0.6) a = legal.canCheck ? { type: 'check' } : { type: 'call' };
      else if (legal.canRaise) a = { type: 'raise', to: legal.minRaiseTo + r.int(Math.max(1, legal.maxRaiseTo - legal.minRaiseTo + 1)) };
      else a = { type: 'call' };
      actions.push(actionToken(a));
      h.act(a);
    }
    emit('hand', seed, n, button, 50, 100, ante, ...stacks, actions.length, ...actions, '|', ...h.seats.map((s) => s.stack), fnv(eventLog(h.events)));
  }
}

