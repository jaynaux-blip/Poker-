function runTourney(spec: TournamentSpec, seed: string, maxTicks: number) {
  const t = new Tournament(spec, 'Hero', seed, [{ name: 'gh0stfold', archetype: 'crusher' }]);
  const specTokens = [spec.id, spec.buyInCents, spec.feeCents, spec.guaranteeCents, spec.entrants, spec.startingStack, spec.levelMinutes, spec.secondsPerHand, spec.population, spec.speed, spec.startClock];
  emit('tourney', seed, maxTicks, ...specTokens);
  // Checkpoint the full state every round so a divergence is pinpointed.
  while (!t.finished && t.tick < maxTicks) {
    if (t.tick === 12) t.moveToTable('npc:gh0stfold', t.hero.tableId);
    const ev = t.simulateTick(sprintProfile());
    let s = '';
    for (const p of t.players.values()) s += `${p.id}:${p.stack}:${p.tableId}:${p.seat}:${p.busted ? p.place : 0};`;
    for (const e of ev) s += `${e.t}:${'place' in e ? e.place : ''}:${'id' in e ? e.id : ''}:${'to' in e ? e.to : ''}:${'tableId' in e ? e.tableId : ''};`;
    emit('tick', seed, t.tick, t.remaining, t.levelIndex, fnv(s));
  }
  const res = [...t.players.values()].map((p) => `${p.id}=${p.busted || p.place === 1 ? p.place : 0}/${p.prizeCents}`);
  emit('tresult', seed, t.tick, t.remaining, t.finished ? 1 : 0, t.prizePoolCents, t.payouts.length, res.length, ...res);
}
