/** Canonical event log; C++ builds the identical string (see golden.cpp). */
export function eventLog(events: HandEvent[]): string {
  let s = '';
  for (const e of events) {
    switch (e.t) {
      case 'ante': s += `A${e.seat},${e.amount};`; break;
      case 'blind': s += `B${e.kind === 'sb' ? 's' : 'b'}${e.seat},${e.amount};`; break;
      case 'deal': s += `D${e.order.join(',')};`; break;
      case 'action': s += `X${STREET[e.street]}${e.seat}${ATYPE[e.type]},${e.added},${e.to},${e.allIn ? 1 : 0},${e.potBefore},${e.facing};`; break;
      case 'street': s += `S${STREET[e.street]}${e.cards.join(',')};`; break;
      case 'return': s += `R${e.seat},${e.amount};`; break;
      case 'reveal': s += `V${e.seats.join(',')};`; break;
      case 'showdown': s += `W${e.hands.map((h) => `${h.seat}:${h.hole.join(',')}:${h.score}`).join('|')};`; break;
      case 'award': s += `P${e.index}/${e.potCount}:${e.pot.amount}:${e.pot.eligible.join(',')}:${e.pot.winners.join(',')}:${e.pot.shares.join(',')};`; break;
      case 'end': s += 'E;'; break;
    }
  }
  return s;
}
