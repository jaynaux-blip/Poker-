// Measures glyph advances in Chromium for the fonts the browser prototype renders with in CI
// (Liberation Sans / DejaVu Sans Mono), so the C++ UI tests lay text out like the prototype does.
// Output: unreal/Plugins/ShortStackCore/Standalone/tests/TestFontMetrics.h
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
const exe = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const browser = await chromium.launch({ executablePath: exe });
const page = await browser.newPage();
const specials = ['·', '—', '–', '…', 'é'];
const data = await page.evaluate((specials) => {
  const c = document.createElement('canvas').getContext('2d');
  const fonts = [
    ['Regular', '500 100px Inter, "Segoe UI", Roboto, Arial, sans-serif'],
    ['Bold', '700 100px Inter, "Segoe UI", Roboto, Arial, sans-serif'],
    ['Mono', '600 100px "JetBrains Mono", Menlo, Consolas, monospace'],
  ];
  const out = {};
  for (const [name, font] of fonts) {
    c.font = font;
    const ascii = [];
    for (let i = 32; i < 127; i++) ascii.push(c.measureText(String.fromCharCode(i)).width);
    const sp = specials.map((s) => c.measureText(s).width);
    const m = c.measureText('Hg');
    out[name] = { ascii, sp, ascent: m.fontBoundingBoxAscent };
  }
  return out;
}, specials);
await browser.close();
const arr = (a) => a.map((v) => v.toFixed(3)).join(', ');
let src = `// Generated by web/scripts/gen-test-font-metrics.mjs. Do not edit.\n// Advance widths at 100 px for ASCII 32..126, then U+00B7, U+2014, U+2013, U+2026, U+00E9.\n#pragma once\n\nnamespace test_font\n{\n`;
for (const [name, d] of Object.entries(data)) {
  src += `const float ${name}Ascii[95] = {${arr(d.ascii)}};\nconst float ${name}Special[5] = {${arr(d.sp)}};\nconst float ${name}Ascent = ${d.ascent.toFixed(3)}f;\n`;
}
src += `} // namespace test_font\n`;
src = src.replace(/(\d+\.\d{3})(?=[,}])/g, '$1f');
const out = new URL('../../unreal/Plugins/ShortStackCore/Standalone/tests/TestFontMetrics.h', import.meta.url).pathname;
writeFileSync(out, src);
console.log('wrote', out);
